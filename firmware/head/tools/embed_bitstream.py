#!/usr/bin/env python3
"""Embed the event-logic bitstream into the MCU image as a C array.

    embed_bitstream.py OUT.c [BITSTREAM.bin]

Search order when no file is given: $RRH_BITSTREAM, then gateware/head_evt/build/head_evt.bin.
If no bitstream exists a zero-length placeholder is generated: the firmware then reports the
event logic as absent (ARM answers FAULT, health SOURCE) instead of failing to build.
The output is deterministic: same input bytes -> same C file.
"""
import hashlib
import os
import sys
from pathlib import Path

REPO = Path(__file__).resolve().parents[3]


def main():
    out = Path(sys.argv[1])
    candidates = [Path(p) for p in sys.argv[2:3]] or \
        ([Path(os.environ["RRH_BITSTREAM"])] if os.environ.get("RRH_BITSTREAM") else []) + \
        [REPO / "gateware" / "head_evt" / "build" / "head_evt.bin"]
    data, source = b"", "none"
    for path in candidates:
        if path.is_file():
            data, source = path.read_bytes(), path.name
            break
    digest = hashlib.sha256(data).hexdigest() if data else ""
    lines = ["/* GENERATED by firmware/head/tools/embed_bitstream.py - DO NOT EDIT. */",
             f"/* source: {source}, {len(data)} bytes, sha256 {digest or 'n/a'} */",
             "#include <stddef.h>", "#include <stdint.h>", "",
             f"const size_t rrh_bitstream_len = {len(data)}u;",
             f"const char rrh_bitstream_sha[] = \"{digest[:16]}\";",
             "const uint8_t rrh_bitstream[] __attribute__((aligned(4))) = {"]
    body = data or b"\x00"
    for i in range(0, len(body), 16):
        lines.append("    " + ", ".join(f"0x{b:02x}" for b in body[i:i + 16]) + ",")
    lines += ["};", ""]
    text = "\n".join(lines)
    if not out.exists() or out.read_text() != text:
        out.parent.mkdir(parents=True, exist_ok=True)
        out.write_text(text)
    print(f"bitstream: {source}, {len(data)} bytes")
    return 0


if __name__ == "__main__":
    sys.exit(main())
