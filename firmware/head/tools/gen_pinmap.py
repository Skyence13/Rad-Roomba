#!/usr/bin/env python3
"""Generate port/stm32g474/rrh_pins.h and the README hardware-mapping table from pinmap.yaml.

    gen_pinmap.py            regenerate both
    gen_pinmap.py --check    exit 1 if a generated file is out of date
"""
import re
import sys
from pathlib import Path

import yaml

HEAD = Path(__file__).resolve().parents[1]
PINMAP = HEAD / "pinmap.yaml"
HEADER = HEAD / "port" / "stm32g474" / "rrh_pins.h"
README = HEAD / "README.md"
BEGIN, END = "<!-- BEGIN PINMAP (generated by tools/gen_pinmap.py) -->", "<!-- END PINMAP -->"


def header(doc):
    out = ["/* GENERATED by firmware/head/tools/gen_pinmap.py from pinmap.yaml - DO NOT EDIT. */",
           "#ifndef RRH_PINS_H", "#define RRH_PINS_H", "",
           "/* <SIGNAL>_PORT = GPIO port, _PIN = bit number, _AF = alternate function (AF pins only),",
           " * _ADC_CH = ADC channel (analog pins only). */"]
    for e in doc["pins"]:
        m = re.fullmatch(r"P([A-G])(\d+)", e["pin"])
        if not m or e["peripheral"] in ("power", "SYS", "RCC"):
            continue
        sig = re.sub(r"[^A-Z0-9_]", "_", e["signal"].upper())
        out.append(f"#define PIN_{sig}_PORT GPIO{m.group(1)} /* {e['pin']}, LQFP100 pin {e['lqfp100']}, {e['peripheral']} */")
        out.append(f"#define PIN_{sig}_PIN {m.group(2)}u")
        if e["af"] != "-":
            out.append(f"#define PIN_{sig}_AF {e['af']}u")
        if "channel" in e:
            out.append(f"#define PIN_{sig}_ADC_CH {e['channel']}u")
    out += ["", "#endif", ""]
    return "\n".join(out)


def table(doc):
    rows = ["| LQFP100 | Pin | Signal | Peripheral | AF | Dir | Electrical note |", "|---:|---|---|---|---|---|---|"]
    for e in sorted(doc["pins"], key=lambda e: e["lqfp100"]):
        per = e["peripheral"] + (f" IN{e['channel']}" if "channel" in e else "")
        rows.append(f"| {e['lqfp100']} | {e['pin']} | `{e['signal']}` | {per} | {e['af']} | {e['dir']} | {e['note']} |")
    return "\n".join(rows)


def main():
    doc = yaml.safe_load(PINMAP.read_text())
    want_header = header(doc)
    readme = README.read_text() if README.exists() else f"{BEGIN}\n{END}\n"
    if BEGIN not in readme:
        print("README.md has no PINMAP markers", file=sys.stderr)
        return 1
    pre, rest = readme.split(BEGIN, 1)
    _, post = rest.split(END, 1)
    want_readme = f"{pre}{BEGIN}\n{table(doc)}\n{END}{post}"
    stale = [p.name for p, want in ((HEADER, want_header), (README, want_readme))
             if not p.exists() or p.read_text() != want]
    if "--check" in sys.argv:
        if stale:
            print("out of date (run tools/gen_pinmap.py):", ", ".join(stale), file=sys.stderr)
            return 1
        print("pinmap outputs are up to date")
        return 0
    HEADER.write_text(want_header)
    README.write_text(want_readme)
    print("generated", HEADER.relative_to(HEAD), "and the README table")
    return 0


if __name__ == "__main__":
    sys.exit(main())
