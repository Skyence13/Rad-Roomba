#!/usr/bin/env python3
"""Generate the packaged contract snapshot from interface/system/contract.yaml.

    python3 tools/snapshot_contract.py            # rewrite rr_bringup/config/contract_snapshot.yaml
    python3 tools/snapshot_contract.py --check    # exit 1 if the packaged file differs from what this would write

The snapshot is a verbatim copy of the listed contract sections (no value is edited or rounded), so
a unit test can require every field to equal the contract.  Never edit the snapshot by hand.
Run inside the container, e.g.  tools/test.sh  does not run this; use
    docker run ... python3 tools/snapshot_contract.py   (see README, "Contract snapshot").
"""
from __future__ import annotations

import argparse
import copy
import sys
from pathlib import Path

import yaml

WS = Path(__file__).resolve().parents[1]
REPO = WS.parent
CONTRACT = REPO / "interface/system/contract.yaml"
SNAPSHOT = WS / "src/rr_bringup/rr_bringup/config/contract_snapshot.yaml"

# Contract paths copied (dotted).  Keep the nesting of the contract: geometry_config reads
# frames.body_rev_e, motion and survey_methods; timing is kept for the time-sync defaults.
SECTIONS = ["frames.body_rev_e", "motion", "timing", "survey_methods"]
HEADER = ("# Generated by ros2_ws/tools/snapshot_contract.py from interface/system/contract.yaml -- do not edit by hand.\n"
          "# tests (rr_bringup/test/test_config.py) fail when any field differs from the contract.\n")


def _get(d, dotted):
    for k in dotted.split("."):
        d = d[k]
    return d


def _put(d, dotted, value):
    keys = dotted.split(".")
    for k in keys[:-1]:
        d = d.setdefault(k, {})
    d[keys[-1]] = value


def build_snapshot(contract: dict) -> dict:
    out = {"source": "interface/system/contract.yaml", "contract_version": contract["contract_version"]}
    for path in SECTIONS:
        _put(out, path, copy.deepcopy(_get(contract, path)))
    return out


def render(contract: dict) -> str:
    return HEADER + yaml.safe_dump(build_snapshot(contract), sort_keys=False, width=100, allow_unicode=True)


def main(argv=None) -> int:
    ap = argparse.ArgumentParser(description=__doc__.split("\n")[0])
    ap.add_argument("--contract", type=Path, default=CONTRACT)
    ap.add_argument("--out", type=Path, default=SNAPSHOT)
    ap.add_argument("--check", action="store_true")
    a = ap.parse_args(argv)
    text = render(yaml.safe_load(a.contract.read_text()))
    if a.check:
        same = a.out.exists() and a.out.read_text() == text
        print(("snapshot up to date: " if same else "SNAPSHOT STALE: ") + str(a.out))
        return 0 if same else 1
    a.out.write_text(text)
    print(f"wrote {a.out}")
    return 0


if __name__ == "__main__":
    sys.exit(main())
