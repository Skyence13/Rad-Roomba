import pcbnew, os
p = os.path.abspath("exp.kicad_pcb")
b = pcbnew.LoadBoard(p)
MM=pcbnew.FromMM
def V(x,y): return pcbnew.VECTOR2I(MM(x),MM(y))
try:
    d = pcbnew.PCB_DIM_ALIGNED(b, pcbnew.PCB_DIM_ALIGNED_T)
    d.SetStart(V(90,110)); d.SetEnd(V(120,110)); d.SetHeight(MM(5)); d.SetLayer(pcbnew.Dwgs_User)
    d.SetUnitsMode(pcbnew.DIM_UNITS_MODE_MM); d.SetPrecision(pcbnew.DIM_PRECISION_X_XX)
    print([n for n in dir(d) if n.startswith('Set')])
    d.Update(); b.Add(d); print("dim text", d.GetText())
except Exception as e: print("dim fail", e)
z=pcbnew.ZONE(b)
ls = pcbnew.LSET(); ls.AddLayer(pcbnew.F_Cu); ls.AddLayer(pcbnew.B_Cu)
z.SetLayerSet(ls); z.SetIsRuleArea(True); z.SetDoNotAllowTracks(True); z.SetDoNotAllowVias(True); z.SetDoNotAllowCopperPour(True); z.SetDoNotAllowFootprints(True); z.SetDoNotAllowPads(False)
print([n for n in dir(z) if n.startswith('Set')])
print([n for n in dir(pcbnew) if 'ZONE_CONNECTION' in n or 'ZONE_FILL' in n or 'HATCH' in n])
t=pcbnew.PCB_TEXT(b); print([n for n in dir(t) if n.startswith('Set')])
print([n for n in dir(pcbnew) if 'GR_TEXT' in n])
a=pcbnew.PCB_SHAPE(b); print([n for n in dir(a) if 'Arc' in n])
v=pcbnew.PCB_VIA(b); print([n for n in dir(v) if n.startswith('Set')])
ds=b.GetDesignSettings(); print([n for n in dir(ds) if 'Origin' in n])
fp=pcbnew.FootprintLoad("/usr/share/kicad/footprints/Connector_JST.pretty","JST_GH_SM06B-GHS-TB_1x06-1MP_P1.25mm_Horizontal")
fp.BuildCourtyardCaches(); bb=fp.GetCourtyard(pcbnew.F_CrtYd).BBox(); print("cy", pcbnew.ToMM(bb.GetLeft()),pcbnew.ToMM(bb.GetTop()),pcbnew.ToMM(bb.GetRight()),pcbnew.ToMM(bb.GetBottom()))
for pad in fp.Pads(): print(pad.GetNumber(), pcbnew.ToMM(pad.GetPosition()), pcbnew.ToMM(pad.GetSize(pcbnew.F_Cu)) if True else '', pad.GetAttribute(), pad.GetDrillSize().x)
