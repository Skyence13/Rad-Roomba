def test_single_lane_predictive_reference_equals_unull():
    l, cal = R.Lane(np.array([1.0]), np.array([1.0])), R.BETA_CAL
    case = N.LaneCase(l, cal, 1.0)
    for U, n, a in ((3.32, 50, 1e-3), (33.2, 100, 1.14e-5)):
        t_ref = N.threshold_rule(case, n, n / U, a, "predictive")
        pc = P.PredictiveCombined([P.LanePost(l, cal, cal.K, U, n, n / U)])
        assert pc.threshold(a) == pytest.approx(t_ref, rel=1e-8)


def test_two_lane_predictive_agrees_with_monte_carlo():
    """Predictive null of two lanes: tail at its own threshold against direct simulation (lanes' U drawn from their
    posteriors, then counts and calibration terms).  Tolerance 4 binomial standard errors."""
    rng = np.random.default_rng(5)
    lanes = [R.cell_lane_weights(s, v=0.03) for s in (0.04375, -0.04375)]
    cals = [R.Cal(b=0.43, K=23.3), R.Cal(b=0.55, K=24.0)]
    U, n = 5.0, 60
    C = R.Combined(lanes, cals, U)
    lps = [P.LanePost(l, c, ci, U, n, n / U) for l, c, ci in zip(lanes, cals, C.c)]
    pc = P.PredictiveCombined(lps)
    a = 0.01
    t = pc.threshold(a)
    M = 400_000
    s = np.zeros(M)
    gsum = np.zeros(M)
    for l, c, ci in zip(lanes, cals, C.c):
        Ui = rng.gamma(n + 0.5, 1.0 / (n / U), M)
        cK = ci / c.K
        NF = sum(w * rng.poisson((c.k * Ui + c.b) * tt) for w, tt in zip(l.w, l.t))
        NU = sum(w * rng.poisson(Ui * tt) for w, tt in zip(l.w, l.t))
        s += cK * (NF / l.T - c.k * NU / l.T - c.b)
        s += cK * rng.normal(0.0, 1.0, M) * np.sqrt(np.maximum(Ui ** 2 * c.u_k_lane ** 2 + c.u_b ** 2 + 2 * Ui * c.cov_kb, 0.0))
        gsum += cK * c.u_k_common * Ui
    s += rng.normal(0.0, 1.0, M) * gsum
    p = float(np.mean(s > t))
    assert p == pytest.approx(a, abs=4 * np.sqrt(a * (1 - a) / M))


def test_cross_term_approximation_is_close_but_not_exact():
    lanes = [R.cell_lane_weights(s, v=0.03) for s in (0.04375, -0.04375)]
    cals = [R.Cal(b=0.43, K=23.3), R.Cal(b=0.55, K=24.0)]
    C = R.Combined(lanes, cals, 33.2)
    lps = [P.LanePost(l, c, ci, 33.2, 200, 200 / 33.2) for l, c, ci in zip(lanes, cals, C.c)]
    te = P.PredictiveCombined(lps).threshold(1e-3)
    ta = P.PredictiveCombined(lps, approx_common=True).threshold(1e-3)
    assert ta < te and abs(ta / te - 1) < 2e-3


def test_one_sided_linear_floor_estimator_holds_alpha_under_gradient_and_keeps_cells():
    case = N.LaneCase(R.Lane(np.array([1.0]), np.array([1.0])), R.BETA_CAL, 1.0)
    U, n = 33.2, 200
    L = 0.1 * n / U
    f = (lambda x: 1.0 - 0.20 * L * x)                    # 20 %/m rising toward the dwell
    ach, lost, dh = N.one_sided_study(case, U, n, 1.14e-5, f, "linear+floor")
    assert ach <= 1.05 and lost == 0.0 and dh < 1.05
    ach_old, _, _ = N.one_sided_study(case, U, n, 1.14e-5, f, "larger")
    assert ach_old > 1.3
    _, lost_guard, _ = N.one_sided_study(case, U, n, 1.14e-5, lambda x: 1.0, "larger+guard")
    assert lost_guard > 0.5                                  # the rev-5 guard discards cells on noise alone


def test_demo_calibration_matches_schema_and_emulated_head():
    jsonschema = pytest.importorskip("jsonschema")
    rec = json.loads((ROOT / "demo_calibration.json").read_text())
    jsonschema.validate(rec, json.loads((ROOT / "schemas" / "calibration_record.schema.json").read_text()))
    ident = rec["identity"]
    assert ident["synthetic"] is True and rec["field_use_approved"] is False
    assert ident["setup_id"] == rec["validity_envelope"]["setup_id"]
    assert rec["validity_envelope"]["speed_m_s"]["max"] > 0.10      # commanded demo speed lies inside the qualified range


def test_predictive_vectors_file_is_consistent():
    path = ROOT / "results" / "rev5_predictive_vectors.json"
    if not path.exists():
        pytest.skip("generated by scripts/s9_rev5_checks.py")
    case = json.loads(path.read_text())["cases"][0]
    lp = case["lanes"][0]
    cal = R.Cal(**{k: lp["cal"][k] for k in ("k", "b", "u_k_lane", "u_k_common", "u_b", "cov_kb", "K")})
    pc = P.PredictiveCombined([P.LanePost(R.Lane(np.array(lp["w"]), np.array(lp["t_s"])), cal, lp["c"], lp["U0"],
                                          lp["posterior"]["N"], lp["posterior"]["T_s"])])
    r = case["results"][1]
    assert pc.threshold(r["alpha"]) == pytest.approx(r["t_star_exact"], rel=1e-6)
