#!/usr/bin/env python3
"""Step 6 - render report/detectability_report.md from the template and the results.

{{V:key}} is replaced by results/summary.json[key]; {{T:name}} by results/tables/name.md.
A missing key or table is an error, so the report cannot silently go stale."""
import json
import re
import sys

from common import RESULTS, ROOT, TABLES

template = (ROOT / "report" / "detectability_report.template.md").read_text(encoding="utf-8")
summary = json.loads((RESULTS / "summary.json").read_text(encoding="utf-8"))
missing = []


def sub(match):
    kind, key = match.group(1), match.group(2)
    if kind == "V":
        if key not in summary:
            missing.append(f"value {key}")
            return "??"
        return summary[key]
    path = TABLES / f"{key}.md"
    if not path.exists():
        missing.append(f"table {key}")
        return "??"
    return path.read_text(encoding="utf-8").rstrip("\n")


text = re.sub(r"\{\{([VT]):([A-Za-z0-9_]+)\}\}", sub, template)
if missing:
    sys.exit("report template refers to missing results: " + ", ".join(missing))
header = "<!-- GENERATED by scripts/s6_report.py from detectability_report.template.md and results/. Edit the template. -->\n"
(ROOT / "report" / "detectability_report.md").write_text(header + text, encoding="utf-8")
print(f"s6: report written ({len(text.split())} words)")
