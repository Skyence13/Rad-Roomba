#!/usr/bin/env python3
"""Latch-drop timing budget and dynamic-braking stopping distance for RR-CHS-MAIN.
Writes electronics/analysis/chassis_braking_tables.md (included by reference in chassis_safety_chain.md).
Tags: [D] datasheet, [C] calculated, [A] assumed, [U] unverified.  Nothing is measured.  Not a certified safety calculation.
"""
import math, os

# ---- motor / vehicle model -------------------------------------------------
M_ROBOT = 12.0                      # kg [D contract ceiling]
R_W = 0.052                         # m  [D contract, 104 mm wheel]
RPM_NL, I_NL, I_STALL, V_R = 67.0, 0.2, 5.5, 12.0      # [D] Pololu #2828
GEAR = 150.0                        # [D]
T_STALL = 49 * 9.80665 / 100.0      # N m [D, extrapolated by Pololu]
R_M = V_R / I_STALL                 # 2.18 ohm [C]
V_NL = RPM_NL / 60 * 2 * math.pi * R_W
KE = (V_R - I_NL * R_M) / V_NL      # V per (m/s) ground speed, one motor [C]
KF_IDEAL = KE                       # N per A at the ground if the gearbox were lossless [C] (power balance)
KF_DRIVE = T_STALL / (I_STALL - I_NL) / R_W            # N per A from the catalogue stall point (gear losses included) [C]
J_ROTOR = (0.5e-6, 1.0e-6, 2.0e-6)  # kg m2 [A/U] armature inertia of the 37D motor: not published; range used
R_BRK = 1.0                         # ohm brake resistor per motor [design choice]
R_PATH = 0.04                       # ohm relay contacts x2 + motor lead + connector [A]
R_TOT = R_M + R_BRK + R_PATH
F_ROLL = 3.5                        # N [A] rolling resistance, Crr 0.03
F_GEAR = 2 * I_NL * KE              # N [C/A] gearbox + brush friction of both motors taken from the no-load current
SPEEDS = (0.20, 0.10, 0.05)

def m_eff(j):
    return M_ROBOT + 2 * j * GEAR ** 2 / R_W ** 2

def brake(v0, kf, friction, j):
    """Return (distance m, time to 1 % of v0 or to standstill s, tau s, peak current A)."""
    m = m_eff(j)
    c = 2 * kf * KE / R_TOT          # N per (m/s): both motors
    tau = m / c
    ipk = KE * v0 / R_TOT
    if friction <= 0:
        return v0 * tau, 4.6 * tau, tau, ipk
    ts = tau * math.log(1 + c * v0 / friction)
    d = tau * (v0 - friction / c * math.log(1 + c * v0 / friction))
    return d, ts, tau, ipk

# ---- timing budget (ms) -----------------------------------------------------
T = {
    "relay_release":   (5.0, "[D] Omron G2RL-2 release 5 ms max, bare coil"),
    "clamp_penalty":   (2.5, "[A] diode + 24 V Zener across each coil: +50 % on the bare-coil release time"),
    "transfer_bounce": (3.0, "[A] NO opens -> NC closes and settles"),
    "k1_release":      (4.0, "[U] Omron G6S-2 release time 4 ms max (recalled, not read)"),
    "efuse_off":       (1.0, "[A] RUN_12V RC (0.1 ms) + TPS25982 turn-off"),
    "bridge_sleep":    (1.0, "[D] DRV8874 tSLEEP 1 ms"),
    "loop_filter":     (1.5, "[C] 10 k x 100 nF = 1 ms RC to the comparator threshold (1.4 tau worst case)"),
    "ssr_off":         (1.0, "[U] photo-MOS turn-off 1 ms max (TLP241A class; datasheet not reachable)"),
    "mcu_tick":        (2.0, "[A] firmware: 1 kHz supervision tick, worst case 2 ticks to drop ARM_PERMIT"),
    "wdg_upper":       (31.6, "[D] TPS3430 tWDU max, CWD = NC, SET0 = 0, SET1 = 1 (23.4-31.6 ms)"),
    "switch_bounce":   (0.0, "contact opening is the event; no debounce in the chain"),
}
def tsum(*k):
    return sum(T[x][0] for x in k)
PATHS = [
    ("Contact element opens (E-stop, HANDS-ON, bumper, dock, cover, selector)", tsum("relay_release", "clamp_penalty", "transfer_bounce")),
    ("HEAD_LOOP or LAB_KEY (comparator + photo-MOS)", tsum("loop_filter", "ssr_off", "relay_release", "clamp_penalty", "transfer_bounce")),
    ("ARM_PERMIT withdrawn by firmware", tsum("mcu_tick", "ssr_off", "relay_release", "clamp_penalty", "transfer_bounce")),
    ("Watchdog (MCU stopped strobing)", tsum("wdg_upper", "ssr_off", "relay_release", "clamp_penalty", "transfer_bounce")),
    ("Total loss of pack power", tsum("relay_release", "clamp_penalty", "transfer_bounce")),
]

def build():
    o = []; A = o.append
    A("<!-- generated by electronics/analysis/chassis_braking.py - do not edit -->\n")
    A("### T1. Model inputs\n")
    A("| Quantity | Value | Tag |\n|---|---:|---|")
    A("| Motor terminal resistance R = 12 V / 5.5 A | %.2f ohm | [C] from [D] Pololu #2828 extrapolated stall |" % R_M)
    A("| No-load ground speed at 12 V (67 rpm, 104 mm wheel) | %.3f m/s | [C] |" % V_NL)
    A("| Back-EMF constant per motor, ground-referred | %.1f V per m/s | [C] |" % KE)
    A("| Motor-level kV (67 rpm x 150 = 10 050 rpm at 11.56 V) | %.0f rpm/V | [C] |" % (RPM_NL * GEAR / (V_R - I_NL * R_M)))
    A("| Force constant, lossless gearbox (power balance) | %.1f N/A | [C] |" % KF_IDEAL)
    A("| Force constant from catalogue stall torque (gear losses included) | %.1f N/A | [C] used as the *conservative* braking constant |" % KF_DRIVE)
    A("| Rotor inertia per motor | %.1f / %.1f / %.1f x 1e-6 kg m2 | [A][U] not published; low / nominal / high |" % tuple(x * 1e6 for x in J_ROTOR))
    A("| Effective translating mass (12 kg + two reflected rotors) | %.1f / %.1f / %.1f kg | [C] |" % tuple(m_eff(j) for j in J_ROTOR))
    A("| Brake resistor per motor | %.1f ohm (2512, 2 W pulse-rated) | design choice |" % R_BRK)
    A("| Brake loop resistance R + Rbrk + contacts/leads | %.2f ohm | [C] |" % R_TOT)
    A("| Friction force, rolling + both gearboxes (from 0.2 A no-load) | %.1f + %.1f N | [A] |" % (F_ROLL, F_GEAR))
    A("")
    A("### T2. Latch-drop timing budget\n")
    A("| Step | Time (ms) | Basis |\n|---|---:|---|")
    for k, (v, b) in T.items():
        A("| %s | %.1f | %s |" % (k, v, b))
    A("")
    A("| Initiating event | Time to VMOT eFuse off (ms) | Time to bridges asleep (ms) | Time to brake resistor connected (ms) |\n|---|---:|---:|---:|")
    for n, t in PATHS:
        pre = t - tsum("relay_release", "clamp_penalty", "transfer_bounce")
        A("| %s | %.1f | %.1f | **%.1f** |" % (n, pre + T["k1_release"][0] + T["efuse_off"][0], pre + T["k1_release"][0] + T["bridge_sleep"][0], t))
    A("\nVMOT removal waits for K1 (the eFuse enable is taken from the K1-switched RUN_12V node); the brake relays do not wait for K1 because their coils are fed through the chain itself.\n")
    A("### T3. Stopping distance after the initiating event (level floor)\n")
    A("Distance = v0 x (time to brake connected) + braking distance. *Conservative*: force constant %.1f N/A, high rotor inertia, no friction, exponential decay taken to standstill (v0 x tau). "
      "*Nominal*: lossless-gear force constant %.1f N/A, nominal inertia, friction %.1f N.\n" % (KF_DRIVE, KF_IDEAL, F_ROLL + F_GEAR))
    A("| v0 (m/s) | Event | Delay travel (mm) | Braking, nominal (mm) | Braking, conservative (mm) | **Total nominal (mm)** | **Total conservative (mm)** | Peak brake current (A) | Time const. cons. (ms) |\n|---:|---|---:|---:|---:|---:|---:|---:|---:|")
    out = {}
    for v in SPEEDS:
        for n, t in (PATHS[0], PATHS[1]):
            dn, tn, taun, ipk = brake(v, KF_IDEAL, F_ROLL + F_GEAR, J_ROTOR[1])
            dc, tc, tauc, _ = brake(v, KF_DRIVE, 0.0, J_ROTOR[2])
            dly = v * t
            out[(v, n)] = (dly + dn * 1000, dly + dc * 1000)
            A("| %.2f | %s | %.1f | %.1f | %.1f | **%.1f** | **%.1f** | %.2f | %.0f |" % (v, n.split(" (")[0], dly, dn * 1000, dc * 1000, dly + dn * 1000, dly + dc * 1000, ipk, tauc * 1000))
    A("")
    A("### T4. Degraded cases\n")
    A("| Case | 0.20 m/s (mm) | 0.10 m/s (mm) | 0.05 m/s (mm) | Model |\n|---|---:|---:|---:|---|")
    def coast(v, f, j):
        return v * v / (2 * f / m_eff(j)) * 1000
    A("| Coast only, both brake paths lost, nominal friction %.1f N | %.0f | %.0f | %.0f | v0^2/(2a), a = F/m_eff |" % ((F_ROLL + F_GEAR,) + tuple(coast(v, F_ROLL + F_GEAR, J_ROTOR[1]) + v * PATHS[0][1] for v in SPEEDS)))
    A("| Coast only, half that friction, high inertia | %.0f | %.0f | %.0f | same |" % tuple(coast(v, (F_ROLL + F_GEAR) / 2, J_ROTOR[2]) + v * PATHS[0][1] for v in SPEEDS))
    A("| Coast only, rolling resistance alone (gearbox friction ignored) | %.0f | %.0f | %.0f | bound, not expected |" % tuple(coast(v, F_ROLL, J_ROTOR[2]) + v * PATHS[0][1] for v in SPEEDS))
    one = []
    for v in SPEEDS:
        m = m_eff(J_ROTOR[2]); c = KF_DRIVE * KE / R_TOT
        one.append(v * (m / c) * 1000 + v * PATHS[0][1])
    A("| One motor braked, the other coasting without friction (robot also yaws) | %.0f | %.0f | %.0f | conservative constant, single motor |" % tuple(one))
    # watchdog / runaway case
    a_run = min(2 * 2.68 * KF_DRIVE, 0.8 * 0.7 * M_ROBOT * 9.81) / m_eff(J_ROTOR[0])
    t_w = PATHS[3][1] / 1000.0
    rows = []
    for v in SPEEDS:
        v1 = v + a_run * t_w
        d = v * t_w + 0.5 * a_run * t_w ** 2 + brake(v1, KF_DRIVE, 0.0, J_ROTOR[2])[0]
        rows.append(d * 1000)
    A("| MCU fails with the bridges driving full torque until the watchdog opens the chain (%.0f ms, accel %.1f m/s2 traction-limited) | %.0f | %.0f | %.0f | conservative |" % ((PATHS[3][1], a_run) + tuple(rows)))
    A("")
    c_cons = 2 * KF_DRIVE * KE / R_TOT
    A("### T5. Slope and holding\n")
    A("Dynamic braking produces force only while moving: braking coefficient %.0f N per m/s (conservative) / %.0f (nominal). It cannot hold a slope. Gearbox friction (%.1f N [A]) holds the stationary robot up to about %.1f deg "
      "(%.1f deg with half the friction); beyond that the unpowered robot creeps at (m g sin(theta) - F_fric) / c, e.g. %.0f mm/s on a 10 deg ramp with half friction. A parking brake is not fitted; the operating envelope must exclude slopes above the measured holding angle (VT open).\n"
      % (c_cons, 2 * KF_IDEAL * KE / R_TOT, F_GEAR, math.degrees(math.asin(F_GEAR / (M_ROBOT * 9.81))), math.degrees(math.asin(F_GEAR / 2 / (M_ROBOT * 9.81))),
         (M_ROBOT * 9.81 * math.sin(math.radians(10)) - F_GEAR / 2) / c_cons * 1000))
    A("### T6. Brake resistor and contact stress\n")
    for v in (0.20, V_NL * 14.4 / 12.0):
        e = 0.5 * m_eff(J_ROTOR[2]) * v * v
        ipk = KE * v / R_TOT
        A("- v0 = %.2f m/s%s: kinetic energy %.2f J (high inertia), peak brake current %.2f A, peak resistor power %.1f W, energy per resistor <= %.2f J. [C]"
          % (v, " (runaway at 14.4 V no-load speed)" if v > 0.3 else "", e, ipk, ipk ** 2 * R_BRK, e / 2 * R_BRK / R_TOT))
    A("- Relay contacts (G2RL-2: 8 A, 30 V DC resistive [D family]) break at most the bridge current limit 2.68 A and make at most the brake current above. [C]")
    A("")
    A("### T7. Regeneration and bus clamp\n")
    e_max = 0.5 * m_eff(J_ROTOR[2]) * (0.20 ** 2)
    p_pk = 2 * 2.68 * KE * 0.20
    A("- Largest energy the drive can return in a controlled stop from 0.20 m/s: %.2f J (all kinetic energy, no losses) [C]. Peak regenerated power if both bridges brake at the current limit: 2 x 2.68 A x %.1f V = %.0f W for a few tens of ms [C]."
      % (e_max, KE * 0.20, p_pk))
    c_bulk = 3 * 270e-6 + 200e-6
    A("- Bus capacitance %.0f uF (VMOT 3 x 270 uF + VBAT_SW): absorbing %.2f J alone would lift 14.4 V to %.1f V [C] - so a clamp is required when nothing else takes the energy (BMS open)."
      % (c_bulk * 1e6, e_max, math.sqrt(14.4 ** 2 + 2 * e_max / c_bulk)))
    A("- Clamp: comparator on VMOT, on at 15.6 V, off at 15.0 V [design], 4.7 ohm -> %.1f A, %.0f W peak at 15.6 V (> %.0f W regenerated). Pulse energy <= %.1f J per stop; a 2512 pulse-withstanding 4.7 ohm pair in parallel (2 x 10 ohm, 2 W each) is ample. [C]"
      % (15.6 / 4.7, 15.6 ** 2 / 4.7, p_pk, e_max))
    A("- With the pack connected and accepting charge the standing load (>= 15 W) is usually larger than the average regenerated power and the bus does not rise; the clamp is for the BMS-open and full-pack cases. [C]")
    A("- Stuck-on clamp: 13 V / 4.7 ohm = 2.8 A, 36 W continuous in a 4 W resistor pair -> a 1.1 A-hold PTC in series trips in a few seconds [A]; BUS_CLAMP_ACTIVE readback and the INA228 offset make it visible. [C]")
    return "\n".join(o) + "\n", out

if __name__ == "__main__":
    md, out = build()
    p = os.path.join(os.path.dirname(os.path.abspath(__file__)), "chassis_braking_tables.md")
    open(p, "w").write(md)
    print(md)
