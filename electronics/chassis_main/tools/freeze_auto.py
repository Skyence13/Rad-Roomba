"""Freeze the auto-arranged parts of the last build: reports/placement.txt [auto] lines -> placement_auto.py.
    python3 electronics/chassis_main/tools/freeze_auto.py
placement.py merges AUTO into PLACE (explicit entries win), so later builds place every part explicitly and the
pre-routes in prerout.py can rely on fixed pad positions.  Delete placement_auto.py to re-run the auto-arranger."""
import os, re
HERE = os.path.dirname(os.path.dirname(os.path.abspath(__file__)))
rows = []
for line in open(os.path.join(HERE, "reports", "placement.txt")):
    m = re.match(r'^(\S+)\s+at=\(([^)]*)\)\s+\[auto\]', line)
    if m:
        rows.append('    "%s": (%s),' % (m.group(1), m.group(2)))
with open(os.path.join(HERE, "placement_auto.py"), "w") as f:
    f.write('"""Generated by tools/freeze_auto.py from reports/placement.txt (auto-arranged passives, frozen).  Edit freely."""\n')
    f.write("AUTO = {\n" + "\n".join(rows) + "\n}\n")
print(len(rows), "parts frozen")
