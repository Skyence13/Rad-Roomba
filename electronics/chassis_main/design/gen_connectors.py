#!/usr/bin/env python3
"""Writes connectors.yaml (harness view of every RR-CHS-MAIN connector) from circuit.py.  No dependencies."""
import os, sys
sys.path.insert(0, os.path.dirname(os.path.abspath(__file__)))
import circuit as c

MATE = {
    "Mini-Fit": dict(family="Molex Mini-Fit Jr 4.20 mm (POWER ENTRY)", housing="39-01-2080", contacts="39-00-0078 (AWG 16) for pins 1/2/5/6; 39-00-0038 (AWG 18-24) for the rest", verify=True),
    "Micro-Fit": dict(family="Molex Micro-Fit 3.0 (POWER)", housing="43025-%02d00", contacts="43030-0007 (AWG 20-24) / 43030-0010 (AWG 26-30)", verify=True),
    "CLIK-Mate": dict(family="Molex CLIK-Mate 2.00 mm (SAFETY, yellow wire)", housing="502439-%02d00", contacts="502438-0000 (AWG 24-30)", verify=True),
    "JST GH": dict(family="JST GH 1.25 mm (SIGNAL)", housing="GHR-%02dV-S", contacts="SSHL-002T-P0.2 (AWG 26-30)", verify=False),
    "Cortex": dict(family="1.27 mm IDC (SERVICE)", housing="Samtec FFSD-05-D-06.00-01-N ribbon", contacts="-", verify=True),
}
by = {p["ref"]: p for p in c.PARTS}
out = ["# RR-CHS-MAIN rev A board connectors -- GENERATED by gen_connectors.py from circuit.py; do not edit.",
       "# Families cannot cross-mate: Mini-Fit Jr (power entry), Micro-Fit 3.0 (power), CLIK-Mate 2.0 (safety chain), JST GH (signal).",
       "# Within a family, connectors with the same circuit count are listed under same_count_as with the consequence of a swap.",
       "# verify: true = mating part number recalled, not confirmed against the manufacturer's catalogue in stage 1.",
       "board: RR-CHS-MAIN", "revision: A", "connectors:"]
SWAP = {"J_HTR": "J_LIDAR: harmless (both VBAT-level outputs; the 1.5 A LiDAR limit trips on the heater)", "J_LIDAR": "J_HTR: harmless, LiDAR then follows the heater enable",
        "J_MOT_L": "J_MOT_R: left/right swapped, found by the first wheel-up test", "J_MOT_R": "J_MOT_L",
        "J_BUMP_L": "J_BUMP_R: no loss of function (series contacts)", "J_BUMP_R": "J_BUMP_L",
        "J_COVER": "J_DOCK: chain stays open (different pins used)", "J_DOCK": "J_COVER: chain stays open",
        "J_USB_MCU": "J_USB_HEAD: both are USB device ports; links enumerate on the other host port, no damage", "J_USB_HEAD": "J_USB_MCU",
        "J_PAUX": "J_NTC / J_DBG (4-pin GH): wrong readings, no damage (all <= 3.3 V through >= 100 ohm)", "J_NTC": "J_PAUX / J_DBG", "J_DBG": "J_PAUX / J_NTC"}
for ref in sorted(c.CONNECTORS):
    p, info = by[ref], c.CONNECTORS[ref]
    fam = next(k for k in MATE if k in p["value"] or k in p["description"])
    m = MATE[fam]
    n = len([k for k in p["pins"] if k != "MP"])
    out.append("  - ref: %s" % ref)
    out.append("    function: \"%s\"" % info["function"])
    out.append("    detail: \"%s\"" % p["description"].replace('"', "'"))
    out.append("    family: \"%s\"" % m["family"])
    out.append("    board_mpn: \"%s %s\"" % (p["manufacturer"], p["mpn"]))
    out.append("    mating_housing: \"%s\"" % (m["housing"] % n if "%" in m["housing"] else m["housing"]))
    out.append("    mating_contacts: \"%s\"" % m["contacts"])
    out.append("    verify: %s" % ("true" if (m["verify"] or p["verify"]) else "false"))
    out.append("    position: \"%s\"" % info["edge"])
    out.append("    max_current_a: %s" % info["max_a"])
    if ref in SWAP:
        out.append("    same_count_as: \"%s\"" % SWAP[ref])
    out.append("    pins:")
    for k in sorted((k for k in p["pins"] if k != "MP"), key=int):
        v = p["pins"][k]
        awg = info["awg"].get(int(k)) if isinstance(info["awg"], dict) else info["awg"]
        out.append("      %s: {net: %s, awg: %s}" % (k, v[1] if v else "NC", awg if (v and awg) else "null"))
open(os.path.join(os.path.dirname(os.path.abspath(__file__)), "connectors.yaml"), "w").write("\n".join(out) + "\n")
print("wrote connectors.yaml: %d connectors" % len(c.CONNECTORS))
