"""Run every calculation and write out/mech_calcs.md, out/gap_measurement_method.md, out/mech_calcs.json."""
from __future__ import annotations

import json
import sys

from .. import params as P
from . import gap, mass_cg, motion, structure, thermal


def main():
    P.OUT.mkdir(exist_ok=True)
    head = ("# Rad Roomba Rev E -- mechanical calculations\n\n"
            f"Generated by `python -m mechanical.common.calc.run_all` from `params.py` (contract {P.CONTRACT_VERSION}). "
            "**Every result in this file is evidence class `calculated`** (closed-form, rigid-body or lumped models with the tabulated inputs); "
            "nothing is simulated by FEA or physically measured. Inputs marked ASSUMED / UNVERIFIED need supplier or test confirmation.\n")
    sections, keys = [head], {}
    for mod in (mass_cg, structure, gap, thermal, motion):
        md, key = mod.run()
        sections.append(md)
        keys[mod.__name__.split(".")[-1]] = key
    (P.OUT / "mech_calcs.md").write_text("\n\n".join(sections) + "\n", encoding="utf-8")
    (P.OUT / "gap_measurement_method.md").write_text(gap.method(keys["gap"]), encoding="utf-8")
    (P.OUT / "mech_calcs.json").write_text(json.dumps(keys, indent=1, default=str), encoding="utf-8")
    # sanity gates (non-zero exit on failure)
    fails = []
    mk = keys["mass_cg"]
    if mk["heaviest_kg"] > P.MASS_GOAL_KG:
        fails.append(f"mass {mk['heaviest_kg']:.2f} kg exceeds {P.MASS_GOAL_KG} kg")
    if keys["motion"]["lookahead_edge_clearance"] <= 0:
        fails.append("look-ahead lower cone edge hits the head")
    print(json.dumps({"heaviest_kg": round(mk["heaviest_kg"], 2), "worst_fwd_tip_mm": round(mk["worst_fwd_tip_mm"], 1), "worst_case": mk["worst_case"],
                      "ballast_kg": mk["ballast_kg"], "cg_range_mm": [round(v, 1) for v in mk["cg_range_mm"]],
                      "gap_band": [round(keys["gap"]["band_lo"], 1), round(keys["gap"]["band_hi"], 1)],
                      "touch_3mm": round(keys["gap"]["touch_3mm"], 1), "touch_5mm": round(keys["gap"]["touch_5mm"], 1),
                      "head_htr": [round(keys["thermal"]["head_htr_m20"]), round(keys["thermal"]["head_htr_m25"])],
                      "chs_htr": [round(keys["thermal"]["chs_htr_m20"]), round(keys["thermal"]["chs_htr_m25"])]}, indent=1))
    if mk["worst_fwd_tip_mm"] <= 0:
        print("WARNING (finding, not a build failure): forward tip margin <= 0 without ballast -- see mech_calcs.md section 1")
    for x in fails:
        print("FAIL", x)
    return 1 if fails else 0


if __name__ == "__main__":
    sys.exit(main())
