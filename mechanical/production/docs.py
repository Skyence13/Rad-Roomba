FLAT = ("chassis_plate", "grip_side_plate", "bridge_tray", "screw_ring", "caster_disc", "caster_shim", "receiver_shim", "latch_arm")


def callout(d, metal):
    d = round(d, 2)
    for m, v in D.TAP.items():
        if abs(d - v) < 0.06 and metal:
            return f"{m}-6H tapped (drill {v})"
    if metal and abs(d - 4.0) < 0.03:
        return "4 H7 reamed"
    for m, v in D.CLEAR.items():
        if abs(d - v) < 0.06:
            return f"{m} clearance {v}"
    if not metal:
        for m, (dd, depth) in D.INSERT.items():
            if abs(d - dd) < 0.06:
                return f"{m} heat-set insert bore {dd} x {depth}"
    return f"dia {d}"


def flat_frame(shape):
    """Rotate a flat part so its thinnest bounding-box axis is z; returns (shape, label)."""
    b = shape.BoundingBox()
    ext = [b.xlen, b.ylen, b.zlen]
    k = ext.index(min(ext))
    if k == 0:
        shape = shape.rotate((0, 0, 0), (0, 1, 0), 90)
    elif k == 1:
        shape = shape.rotate((0, 0, 0), (1, 0, 0), 90)
    return shape


def flat_profile(p):
    """(shape in flat frame, outer polylines, holes [(x, y, d)], other inner polylines, thickness, origin label)."""
    s = p.shape if p.name == "chassis_plate" else flat_frame(p.shape)
    b = s.BoundingBox()
    zmid = (b.zmin + b.zmax) / 2 if p.name != "chassis_plate" else 33.2          # plate: just above the underside (pockets show)
    sec = cq.Workplane("XY").add(s).section(zmid).val()
    ox, oy = (0.0, 0.0) if p.name == "chassis_plate" else (b.xmin, b.ymin)
    outer, holes, inner = [], [], []
    for f in sec.Faces():
        outer.append(_wire_pts(f.outerWire(), ox, oy))
        for w in f.innerWires():
            es = w.Edges()
            if len(es) == 1 and es[0].geomType() == "CIRCLE":
                c = es[0].arcCenter()
                holes.append((round(c.x - ox, 2), round(c.y - oy, 2), round(2 * es[0].radius(), 2)))
            else:
                inner.append(_wire_pts(w, ox, oy))
    return s, outer, holes, inner, b.zlen, ("base_link x, y (mm)" if p.name == "chassis_plate" else "lower-left corner of the flat blank")


def _wire_pts(w, ox, oy):
    pts = []
    for e in w.Edges():
        n = 2 if e.geomType() == "LINE" else 16
        pts += [(e.positionAt(i / (n - 1)).x - ox, e.positionAt(i / (n - 1)).y - oy) for i in range(n)]
    return pts


def write_dxf(parts):
    import ezdxf
    from mechanical.prototype_x1c.rrx.structure import plate_holes, sole_screw_xy
    d = HERE / "dxf"
    d.mkdir(exist_ok=True)
    for f in d.glob("*.dxf"):
        f.unlink()
    done, n = set(), 0
    purpose = {}
    for x, y, dia, kind, why in plate_holes() + [(x, y, D.CLEAR["M3"], "csk_bottom", "lower-hull sole ring M3") for x, y in sole_screw_xy()]:
        purpose[(round(x, 1), round(y, 1))] = (kind, why)
    for p in parts:
        key = next((k for k in FLAT if p.name.startswith(k)), None)
        if not key or p.pn in done or p.kind != "fabricated":
            continue
        done.add(p.pn)
        s, outer, holes, inner, t, origin = flat_profile(p)
        doc = ezdxf.new("R2010")
        doc.units = ezdxf.units.MM
        for lay, col in (("CUT", 7), ("HOLES", 1), ("INNER", 3), ("TEXT", 5)):
            doc.layers.add(lay, color=col)
        msp = doc.modelspace()
        for poly in outer:
            msp.add_lwpolyline(poly, close=True, dxfattribs={"layer": "CUT"})
        for poly in inner:
            msp.add_lwpolyline(poly, close=True, dxfattribs={"layer": "INNER"})
        metal = not p.material.startswith(("G10", "PA"))
        rows = []
        for i, (x, y, dia) in enumerate(sorted(holes, key=lambda h: (h[0], h[1])), 1):
            msp.add_circle((x, y), dia / 2, dxfattribs={"layer": "HOLES"})
            msp.add_text(f"H{i}", height=1.6, dxfattribs={"layer": "TEXT"}).set_placement((x + dia / 2 + 0.5, y + 0.5))
            k, why = purpose.get((round(x, 1), round(y, 1)), ("", ""))
            rows.append((f"H{i}", x, y, dia, (k + " " if k else "") + callout(dia, metal), why))
        bb = s.BoundingBox()
        x0 = (bb.xmax if p.name == "chassis_plate" else bb.xlen) + 15
        lines = [f"{p.pn}  {p.name}  material {p.material}, t = {t:.2f} mm, process: {p.process_class}", f"finish: {p.finish}",
                 f"origin: {origin}; general tolerance ISO 2768-mK, profile +-0.1; units mm; generated by mechanical/production/docs.py",
                 "HOLE TABLE: id | x | y | dia | operation / call-out | purpose"]
        lines += [f"{r[0]} | {r[1]:.2f} | {r[2]:.2f} | {r[3]:.2f} | {r[4]} | {r[5]}" for r in rows]
        if inner:
            lines.append(f"+ {len(inner)} non-circular cut-outs / pockets on layer INNER (see drawing)")
        y0 = (bb.ymax if p.name == "chassis_plate" else bb.ylen)
        for i, ln in enumerate(lines):
            msp.add_text(ln, height=2.0, dxfattribs={"layer": "TEXT"}).set_placement((x0, y0 - 3.0 * i))
        doc.saveas(d / f"{p.pn}_{key}.dxf")
        with open(d / f"{p.pn}_{key}_holes.csv", "w", newline="", encoding="utf-8") as fh:
            w = csv.writer(fh)
            w.writerow(["id", "x_mm", "y_mm", "dia_mm", "operation", "purpose"])
            w.writerows(rows)
        n += 1
    return n


