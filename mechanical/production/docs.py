def process_envelope(p):
    e = ENVELOPES.get(getattr(p, "process_class", None))
    return (e[0], e[1]) if e else (None, None)


def robot(parts):
    return [p for p in parts if p.group not in ROBOT_EXCLUDE]


def unique_made(parts):
    recs = E.unique_parts([p for p in parts if p.group != "tray"], "fabricated")
    for r in recs:
        r["file"] = r["file"].replace("/", "_")
    return recs


