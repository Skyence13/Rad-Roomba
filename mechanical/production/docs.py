def export_assemblies(parts, limit_mb):
    """Full assembly with the production head to out/ (untracked when over the limit) and per-subassembly STEPs to assembly/."""
    (HERE / "assembly").mkdir(exist_ok=True)
    info = {}
    real = HERE.parent / "head" / "production" / "RR-HD-P-000_head_assembly_production.step"
    asm = cq.Assembly(name="RRP_production_body")
    for p in parts:
        if p.group in ("tray",) or (real.exists() and p.group == "head_placeholder"):
            continue
        asm.add(p.shape, name=p.name, color=cq.Color(p.color) if isinstance(p.color, str) else None)
    if real.exists():
        try:
            objs = cq.importers.importStep(str(real)).vals()
            asm.add(cq.Compound.makeCompound([o for o in objs if isinstance(o, cq.Shape)]), name="head_RR-HD-P-000_production_from_mechanical_head", color=cq.Color(0.2, 0.3, 0.32, 1.0))
        except Exception as e:  # noqa: BLE001
            print(f"  production head STEP not added: {e}")
    full = OUT / "RRP-000_assembly_full.step"
    asm.export(str(full))
    info["full assembly (with production head)"] = {"path": str(full.relative_to(HERE)), "mb": full.stat().st_size / 1e6, "untracked": True}
    rest = {p.group for p in parts} - set().union(*SUBASM.values()) - ROBOT_EXCLUDE - {"tray"}
    groups = dict(SUBASM)
    groups["RRP-400_electronics_controls_purchased"] = rest
    for name, gs in groups.items():
        a = cq.Assembly(name=name)
        n = 0
        for p in parts:
            if p.group in gs:
                a.add(p.shape, name=p.name, color=cq.Color(p.color) if isinstance(p.color, str) else None)
                n += 1
        path = HERE / "assembly" / f"{name}.step"
        a.export(str(path))
        mb = path.stat().st_size / 1e6
        if mb > limit_mb:
            dest = OUT / path.name
            path.replace(dest)
            path = dest
        info[name] = {"path": str(path.relative_to(HERE)), "mb": mb, "untracked": mb > limit_mb, "parts": n}
    (HERE / "assembly" / "README.md").write_text(
        "# Production assembly STEP files\n\nPer-subassembly STEP in base_link (tracked). The full assembly with the production head "
        f"(`out/RRP-000_assembly_full.step`, {info['full assembly (with production head)']['mb']:.0f} MB) is regenerated by `build.sh` and not tracked.\n\n"
        "| File | Parts | MB |\n|---|---|---|\n" + "\n".join(f"| {v['path']} | {v.get('parts', '-')} | {v['mb']:.1f} |" for k, v in info.items() if k.startswith("RRP")) + "\n", encoding="utf-8")
    return info


