# ------------------------------------------------------------------------------------------------- hardware
def production_hardware():
    out = []
    for r in HW.rows():
        r = dict(r)
        wh = r["where"]
        if "flanges" in wh and "nose/shoulder" in wh:
            continue                                                   # lid joints x = 47 / x = -38 do not exist (one-piece lid)
        if r["item"] == "dowel pin" and "lid joint" in wh:
            continue
        if "hump walls" in wh:
            continue                                                   # hump is part of the lid
        if "motor pod inserts" in wh:
            r["where"] = "plate (from below) -> M4 tapped in the machined pod (8 deep)"
        if r["item"] == "tyre adhesive":
            r.update(item="adhesion primer", spec="PU-to-aluminium primer (tyre cast onto the keyed rim)", where="rim keys before casting", status="UNVERIFIED")
        if r["item"] == "flat gasket sheet":
            r["where"] = "front bulkhead / nose chin and pod notches only (lid and hull are one piece each)"
            r["spec"] = "closed-cell silicone 1.0 mm, 150 x 150"
        if r["item"] == "heat-set insert":
            m = r["spec"].split()[0]
            r["qty"] = r["qty"] - (8 + 2 * len(HUMP_SCREW_X) if m == "M3" else 8 if m == "M4" else 0)
            r["spec"] = r["spec"].replace("brass, knurled", "brass, knurled, for SLS PA11 (heat-set or ultrasonic)")
            r["where"] = "SLS parts (serviced joints only)"
        if r["item"] == "insulation liner":
            r["where"] = "inside of the one-piece lid, lower hull and door (m2)"
        r["where"] = r["where"].replace("printed pockets", "SLS pockets").replace("printed", "SLS")
        out.append(r)
    return [r for r in out if not (isinstance(r["qty"], (int, float)) and r["qty"] <= 0)]


FASTENER_WORDS = ("screw", "pin", "nut", "insert", "plunger", "washer", "bushing")


def fastener_count(rows):
    n = {"threaded fasteners (screws, nuts)": 0, "pins and dowels": 0, "heat-set inserts": 0, "washers and bushings": 0}
    for r in rows:
        if r["subassembly"].startswith("K") or not isinstance(r["qty"], int):
            continue
        it = (r["item"] + " " + r["spec"]).lower()
        if "insert" in r["item"].lower():
            n["heat-set inserts"] += r["qty"]
        elif "washer" in r["item"].lower() or "bushing" in r["item"].lower():
            n["washers and bushings"] += r["qty"]
        elif "pin" in r["item"].lower() and "screw" not in r["item"].lower():
            n["pins and dowels"] += r["qty"]
        elif "screw" in it or "nut" in it or "plunger" in it:
            n["threaded fasteners (screws, nuts)"] += r["qty"]
    n["total"] = sum(n.values())
    return n


def write_hardware():
    rows = production_hardware()
    with open(HERE / "hardware_production.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    A = ["# RR-P production body: hardware list by sub-assembly\n",
         "Generated by `mechanical/production/docs.py` from the prototype hardware model (`prototype_x1c/rrx/hardware.py`, same hole lists) with the production "
         "changes applied: no lid joints (x 47 / x -38), no hump screws, no hull splice; motor pods tapped instead of inserts; tyre cast on. "
         "STD = standard part; UNVERIFIED = supplier number or a dimension it depends on not confirmed; DESIGN = defined by this model.\n"]
    cur = None
    for h in rows:
        if h["subassembly"] != cur:
            cur = h["subassembly"]
            A.append(f"\n## {cur}\n\n| Item | Specification | Qty | Where | Torque (N m) | Status | Note |\n|---|---|---|---|---|---|---|")
        A.append(f"| {h['item']} | {h['spec']} | {h['qty']} | {h['where']} | {h['torque_Nm']} | {h['status']} | {h['note']} |")
    fc = fastener_count(rows)
    A.append("\n**Fastener count (calculated from the list, transport tray excluded):** " + ", ".join(f"{k} {v}" for k, v in fc.items()))
    (HERE / "hardware_production.md").write_text("\n".join(A) + "\n", encoding="utf-8")
    return rows


# ------------------------------------------------------------------------------------------------- BOM
def write_bom(parts, made):
    rows = []
    for rec in made:
        p = rec["part"]
        rows.append({"part_number": p.pn, "part": rec["file"], "instances": " ".join(rec["instances"]), "qty": rec["qty"], "make_buy": "MAKE", "process": p.process_class,
                     "tooling": p.tooling, "material": p.material, "finish": p.finish, "mass_each_g": round(mass_of(p) * 1000, 1), "replaces_in_x1c_build": getattr(p, "replaces", ""),
                     "x1c_pn": p.x1c_pn, "drawing": "drawings/RRP_fabrication_drawings.pdf", "step": f"step/{p.pn}_{rec['file']}.step", "status": "DESIGN"})
    for rec in E.unique_parts([q for q in parts if q.group not in ROBOT_EXCLUDE and q.material != "KEEPOUT" and not q.name.endswith("_operator")], "purchased"):
        p = rec["part"]
        st = p.verified or "see parts.yaml"
        if "VERIFIED" not in st.upper() and "standard" not in st.lower() and "contract" not in st.lower():
            st = "UNVERIFIED: " + st
        rows.append({"part_number": p.pn, "part": rec["file"], "instances": " ".join(rec["instances"]), "qty": rec["qty"], "make_buy": "BUY", "process": "purchased",
                     "tooling": "-", "material": p.material, "finish": "-", "mass_each_g": round(mass_of(p) * 1000, 1), "replaces_in_x1c_build": "same part",
                     "x1c_pn": p.x1c_pn, "drawing": "", "step": "", "status": st + (f" ({p.mpn})" if p.mpn else "")})
    with open(HERE / "bom_production.csv", "w", newline="", encoding="utf-8") as fh:
        w = csv.DictWriter(fh, fieldnames=list(rows[0].keys()))
        w.writeheader()
        w.writerows(rows)
    md = ["# RR-P production body: bill of materials\n", "Generated by `mechanical/production/docs.py`. MAKE parts: one STEP each in `step/` (base_link), drawings in "
          "`drawings/RRP_fabrication_drawings.pdf`, flat parts also in `dxf/`. Hardware (screws, inserts, seals): `hardware_production.md`. Masses calculated "
          "(CAD volume x density; SLS parts fully dense, 1.04 g/cm3 UNVERIFIED).\n",
          "| PN | Part | Qty | Make/buy | Process | Tooling | Material | Finish | Mass each (g) | Replaces (X1C build) |", "|---|---|---|---|---|---|---|---|---|---|"]
    for r in rows:
        md.append(f"| {r['part_number']} | {r['part']} | {r['qty']} | {r['make_buy']} | {r['process']} | {r['tooling']} | {r['material']} | {r['finish']} | {r['mass_each_g']} | {r['replaces_in_x1c_build']} |")
    (HERE / "bom_production.md").write_text("\n".join(md) + "\n", encoding="utf-8")
    return rows


