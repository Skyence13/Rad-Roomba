def _content(parts, kind_fn):
    """Per-unit process content: {process: [pieces, volume cm3, bounding-box volume cm3]}."""
    out = {}
    for p in robot(parts):
        if p.kind not in ("printed", "fabricated"):
            continue
        k = kind_fn(p)
        b = p.bb
        r = out.setdefault(k, [0, 0.0, 0.0])
        r[0] += 1
        r[1] += p.volume / 1000
        r[2] += (b[3] - b[0]) * (b[4] - b[1]) * (b[5] - b[2]) / 1000
    return out


