"""As-built RR-HEAD-ACQ placement, read from the KiCad board file (machine-readable source for the board-fit check).

Source: electronics/head_acq/RR-HEAD-ACQ.kicad_pcb (generated by electronics/head_acq/board.py + layout.py). Frame mapping from
electronics/head_acq/README.md section 2: board (u, v) = (X - aux_axis_origin_x, aux_axis_origin_y - Y); base_link = (83.2 + v, 163.0 - u,
34.5 + z). Heights = the 3D envelope height the electronics build attached to each footprint (3d/<fp>_h<h>.step), i.e. the
values the electronics build uses (Micro-Fit 6.0 mm is UNVERIFIED there, CCR-HE-02).

Every number here is READ from the board file; nothing is typed. Evidence class of anything derived: tool-checked against the board file.
"""
from __future__ import annotations

import math
import re
import time
from functools import lru_cache
from pathlib import Path

REPO = Path(__file__).resolve().parents[2]
PCB = REPO / "electronics" / "head_acq" / "RR-HEAD-ACQ.kicad_pcb"


def _xform(at, lx, ly):
    """KiCad footprint-local (lx, ly) -> board (X, Y) for a footprint at (x, y, rot deg); KiCad y points down."""
    x, y, r = at
    a = math.radians(r)
    return x + lx * math.cos(a) + ly * math.sin(a), y - lx * math.sin(a) + ly * math.cos(a)


def _bbox(pts):
    xs, ys = [p[0] for p in pts], [p[1] for p in pts]
    return (min(xs), min(ys), max(xs), max(ys)) if pts else None


def _layer_points(blk, layer):
    """Corner points of every fp_line / fp_rect / fp_poly drawn on the given footprint layer (footprint-local frame)."""
    pts = []
    for m in re.finditer(r"\((fp_line|fp_rect|fp_poly)\s(.*?)\(layer \"([^\"]+)\"\)", blk, re.S):
        if m.group(3) != layer:
            continue
        body = m.group(2)
        for s in re.finditer(r"\((?:start|end|xy) ([-\d.]+) ([-\d.]+)\)", body):
            pts.append((float(s.group(1)), float(s.group(2))))
    return pts


@lru_cache(maxsize=1)
def load(path: str = str(PCB)):
    """{ref: {u, v, rot, side, fp, height, crtyd_uv (u0, v0, u1, v1), fab_uv, fab_rects_uv [...]}} + meta. Retries once if the file is being
    rewritten by the electronics build (read must parse completely)."""
    for attempt in range(3):
        txt = Path(path).read_text()
        if txt.rstrip().endswith(")") and "(aux_axis_origin" in txt:
            break
        time.sleep(5)
    m = re.search(r"\(aux_axis_origin ([-\d.]+) ([-\d.]+)\)", txt)
    ox, oy = float(m.group(1)), float(m.group(2))
    out = {}
    for blk in re.split(r"\n\t\(footprint ", txt)[1:]:
        fp = blk.split("\n", 1)[0].strip().strip('"')
        ref = re.search(r'\(property "Reference" "([^"]+)"', blk).group(1)
        a = re.search(r"\n\t\t\(at ([-\d.]+) ([-\d.]+)(?: ([-\d.]+))?\)", blk)
        at = (float(a.group(1)), float(a.group(2)), float(a.group(3) or 0.0))
        side = "B" if '(layer "B.Cu")' in blk.split("\n")[1] else "F"
        mod = re.search(r'\(model "([^"]+)"', blk)
        hm = re.search(r"_h(\d+)p(\d+)\.step", mod.group(1)) if mod else None
        rec = {"u": round(at[0] - ox, 4), "v": round(oy - at[1], 4), "rot": at[2], "side": side, "fp": fp,
               "height": float(f"{hm.group(1)}.{hm.group(2)}") if hm else None}
        for key, layer in (("crtyd_uv", "F.CrtYd"), ("fab_uv", "F.Fab"), ("b_crtyd_uv", "B.CrtYd"), ("b_fab_uv", "B.Fab")):
            pts = [_xform(at, lx, ly) for lx, ly in _layer_points(blk, layer)]
            bb = _bbox(pts)
            rec[key] = (round(bb[0] - ox, 4), round(oy - bb[3], 4), round(bb[2] - ox, 4), round(oy - bb[1], 4)) if bb else None
        rects = []
        for r_ in re.finditer(r"\(fp_rect\s*\(start ([-\d.]+) ([-\d.]+)\)\s*\(end ([-\d.]+) ([-\d.]+)\)(.*?)\(layer \"F.Fab\"\)", blk, re.S):
            p0, p1 = _xform(at, float(r_.group(1)), float(r_.group(2))), _xform(at, float(r_.group(3)), float(r_.group(4)))
            rects.append((round(min(p0[0], p1[0]) - ox, 4), round(oy - max(p0[1], p1[1]), 4), round(max(p0[0], p1[0]) - ox, 4), round(oy - min(p0[1], p1[1]), 4)))
        rec["fab_rects_uv"] = rects
        pads, pad_info = [], []
        for pb in re.split(r"\n\t\t\(pad ", blk)[1:]:
            pm = re.match(r"\"([^\"]*)\" (\w+) (\w+)\s*\(at ([-\d.]+) ([-\d.]+)", pb)
            if not pm:
                continue
            px, py = _xform((at[0], at[1], at[2]), float(pm.group(4)), float(pm.group(5)))
            sz = re.search(r"\(size ([-\d.]+) ([-\d.]+)\)", pb)
            net = re.search(r'\(net (?:\d+ )?"([^"]*)"\)', pb)
            pads.append((pm.group(1), round(px - ox, 4), round(oy - py, 4)))
            pad_info.append({"num": pm.group(1), "u": round(px - ox, 4), "v": round(oy - py, 4), "shape": pm.group(3),
                             "size": (float(sz.group(1)), float(sz.group(2))) if sz else None, "net": net.group(1) if net else None})
        rec["pads_uv"] = pads
        rec["pads"] = pad_info
        out[ref] = rec
    zones = {}
    for zm in re.finditer(r"\n\t\(zone\b(.*?)\n\t\)", txt, re.S):
        z = zm.group(1)
        nm = re.search(r'\(name "([^"]+)"\)', z)
        if nm and nm.group(1).startswith("KO_H28"):
            pts = [(float(a_) - ox, oy - float(b_)) for a_, b_ in re.findall(r"\(xy ([-\d.]+) ([-\d.]+)\)", z)]
            zones[nm.group(1)] = pts
    st = Path(path).stat()
    meta = {"file": str(Path(path).relative_to(REPO)), "bytes": st.st_size, "mtime_utc": time.strftime("%Y-%m-%d %H:%M:%S", time.gmtime(st.st_mtime)),
            "aux_axis_origin": (ox, oy), "footprints": len(out), "hole_keepouts": zones}
    return out, meta


def to_base(u, v, z=0.0):
    """Board (u, v) -> base_link (electronics/head_acq/README.md section 2)."""
    return 83.2 + v, 163.0 - u, 34.5 + z


def uv_box_to_base(b):
    """(u0, v0, u1, v1) -> base (x0, x1, y0, y1)."""
    x0, y1 = to_base(b[0], b[1])[:2]
    x1, y0 = to_base(b[2], b[3])[:2]
    return x0, x1, y0, y1
